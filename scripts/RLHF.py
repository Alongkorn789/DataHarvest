    chosen = data["chosen"]

    # ดึงคำตอบที่มนุษย์ปฏิเสธ (แย่กว่า/อันตรายกว่า)
    rejected = data["rejected"]


    # การเตรียมข้อมูลเข้าโมเดล (Tokenization)
    # แปลงข้อความที่ดีให้เป็นตัวเลขที่ distilbert เข้าใจ
    chosen_inputs = rm_tokenizer(chosen, return_tensors="pt", padding=True, truncation=True).to(device)


    # ทำแบบเดียวกันกับข้อความที่แย่ เพื่อให้ได้ขนาด Tensor ที่พร้อมส่งเข้าโมเดล
    # แปลงข้อความที่แย่ให้เป็นตัวเลขที่ distilbert เข้าใจ   
    rejected_inputs = rm_tokenizer(rejected, return_tensors="pt", padding=True, truncation=True).to(device)

    
    # การคำนวณคะแนน (Scoring)
    # หมายเหตุ: ในจุดนี้โมเดลอาจจะยังให้คะแนนสลับกันอยู่ เพราะเพิ่งเริ่มฝึก
    # ส่งคำตอบที่ดีเข้าโมเดล เพื่อให้คำนวณ "คะแนนความพึงพอใจ" ออกมา (ค่าควรจะสูง)
    score_c = reward_model(
       input_ids=chosen_inputs["input_ids"],
       attention_mask=chosen_inputs["attention_mask"]
    )

    
    # ส่งคำตอบที่แย่เข้าโมเดล เพื่อให้คำนวณคะแนนออกมา (ค่าควรจะต่ำ)
    score_r = reward_model(
       input_ids=rejected_inputs["input_ids"],
       attention_mask=rejected_inputs["attention_mask"]
    )


    # การคำนวณความผิดพลาด (Loss Calculation)
    # นำคะแนนทั้งคู่เข้าสูตร Bradley-Terry เพื่อหาว่ากรรมการ (Reward Model) ทาย "ลำดับ" ผิดไปมากน้อยแค่ไหน
    # ถ้าโมเดลให้คะแนน rejected สูงกว่า chosen ค่า Loss จะสูงมาก เพื่อบอกโมเดลว่า "ตัดสินใจผิดแล้ว!"
    loss = compute_bt_loss(score_c, score_r)

    # การอัปเดตน้ำหนัก (Backpropagation)
    # ล้างค่าความชันเก่าในหน่วยความจำ
    optimizer_rm.zero_grad()

    # คำนวณว่าต้องปรับพารามิเตอร์ตัวไหนบ้าง เพื่อให้ครั้งหน้า score_c สูงขึ้น และ score_r ต่ำลง
    loss.backward()

    # ทำการปรับค่า Weight จริงๆ ตามที่คำนวณไว้
    # ลูปนี้คือการทำ "ข้อสอบเปรียบเทียบ" ซ้ำๆ เพื่อสอนกรรมการว่า
    # ถ้าเจอประโยคแนว chosen ให้คะแนนเยอะๆ นะ แต่ถ้าเจอแนว rejected ให้คะแนนน้อยๆ
    # จบขั้นตอนนี้ Reward Model จะพร้อมทำหน้าที่เป็น "ครูฝึก" ให้กับ Policy Model ในขั้นตอน PPO ต่อไป
    optimizer_rm.step()

