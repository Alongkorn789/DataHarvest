    # เป็นการบอก Python ว่าเราจะเข้าถึงและใช้งานตัวแปร policy_old ที่อยู่นอกฟังก์ชันนี้
    # ในอัลกอริทึม PPO เราต้องมีโมเดล 2 ตัวเสมอ คือโมเดลที่เรากำลังฝึก (Policy Model) และโมเดลร่างเดิม (Old Policy)
    # เพื่อใช้เปรียบเทียบว่าการอัปเดตใหม่ดีขึ้นหรือแย่ลงอย่างไร การใช้ global ช่วยให้เราสามารถอัปเดต "ร่างเดิม" ให้ทันสมัยตามร่างใหม่ได้เมื่อจบแต่ละ Step
    global policy_old

    # เปลี่ยนโมเดลให้อยู่ในโหมด ประเมินผล (Evaluation Mode)
    # ในขณะที่โมเดลกำลังสร้างคำตอบ (Generate) เราไม่ต้องการให้เลเยอร์อย่าง Dropout ทำงาน
    # เพราะเราต้องการคำตอบที่มีความเสถียรและคงเส้นคงวาที่สุด เพื่อให้นำไปคำนวณ Log-Probability ได้อย่างแม่นยำ
    # การจัดห้องสอบให้เงียบสงบ (Eval mode)
    policy_model.eval()

    # แปลงข้อความคำถาม (prompt) ให้กลายเป็นตัวเลข (Tokens) และส่งไปยัง GPU/CPU
    # บรรทัดนี้เตรียม "วัตถุดิบ" ให้พร้อมสำหรับการส่งเข้าโมเดลเพื่อเริ่มการ Generate
    # การยื่นโจทย์ข้อสอบให้โมเดล
    inputs = policy_tokenizer(prompt, return_tensors="pt").to(device)

    # การสร้างคำตอบ (Generation)
    # ขั้นตอนที่ AI "คิด" และเขียนคำตอบออกมา
    # โมเดลจะทำนายคำถัดไปทีละคำ (Autoregressive)
    # ต่อท้ายคำถามไปเรื่อยๆ จนกว่าจะครบ 50 คำ (max_length) หรือเจอจุดสิ้นสุดประโยค
    # pad_token_id ระบุว่าถ้าประโยคสั้นกว่าที่กำหนด ให้ใช้ eos_token ในการเติมช่องว่าง เพื่อไม่ให้โมเดลสับสน
    # การที่โมเดลนั่งทำข้อสอบจนเสร็จ
    output_ids = policy_model.generate(
        **inputs,
        max_length=50,
        pad_token_id=policy_tokenizer.eos_token_id
    )

    # แปลงตัวเลขผลลัพธ์กลับมาเป็นข้อความภาษาคนที่อ่านออก
    # การนำกระดาษคำตอบที่ได้ไปพิมพ์ออกมาเพื่อเตรียมส่งให้ครูตรวจ
    # ขั้นตอนถัดไปในโค้ดจะเป็นการนำ text นี้ไปให้ reward_model ตรวจสอบ
    text = policy_tokenizer.decode(output_ids[0], skip_special_tokens=True)

    # reward

    # การ "ประเมินผล" และ "เปรียบเทียบ" เพื่อเตรียมอัปเดตโมเดล
    # with torch.no_grad()ใช้โหมดนี้เพราะแค่ต้องการ "คะแนน" จาก Reward Model เท่านั้น
    # ไม่ได้จะฝึกหรืออัปเดตน้ำหนักของตัวกรรมการในตอนนี้ การปิด Grad จะช่วยประหยัด Memory และทำให้ทำงานเร็วขึ้น
    with torch.no_grad():

        # reward_inputs = ... นำข้อความที่โมเดลเพิ่งตอบออกมา (text) ไปเข้า Tokenizer ของฝั่ง Reward Model
        reward_inputs = rm_tokenizer(text, return_tensors="pt", truncation=True).to(device)

        # reward = reward_model(...) ส่งเข้ากรรมการเพื่อพ่นคะแนนออกมา
        # ตัวเลขนี้จะบอกว่าคำตอบนี้ "ดี" หรือ "สุภาพ" แค่ไหนตามเกณฑ์ที่ถูกฝึกมา
        reward = reward_model(**reward_inputs)

    # old log prob (correct)
    # การคำนวณความน่าจะเป็นของ "ร่างเก่า" (Baseline)
    # ใช้ policy_old (ร่างที่ก๊อปปี้ไว้ก่อนเริ่ม Step นี้) คำนวณดูว่า "ความมั่นใจ" เดิมในประโยคนี้มีค่าเท่าไหร่
    # ค่านี้จะถูกใช้เป็นจุดอ้างอิง เพื่อดูว่าในการอัปเดตครั้งนี้ โมเดลตัวใหม่มีความมั่นใจเพิ่มขึ้นหรือลดลงอย่างไรเมื่อเทียบกับของเดิม
    with torch.no_grad():
        old_logprob = compute_log_probs(policy_old, output_ids)

    # new log prob
    # การคำนวณความน่าจะเป็นของ "ร่างใหม่" (Active Learning)
    # policy_model.train(): เปิดโหมดฝึกฝนเพราะเราต้องการคำนวณความชัน (Gradients) เพื่อใช้อัปเดตน้ำหนักในขั้นตอนนี้
    # new_logprob: คำนวณความน่าจะเป็นของประโยคเดิม แต่ใช้ โมเดลตัวปัจจุบัน ที่กำลังจะถูกปรับจูน
    policy_model.train()
    new_logprob = compute_log_probs(policy_model, output_ids)

    # การคำนวณ Ratio (หัวใจของ PPO)
    # หาค่า "สัดส่วนความต่าง" ระหว่างโมเดลใหม่และโมเดลเก่า
    # Ratio > 1: โมเดลใหม่ "มั่นใจ" ในคำตอบนี้มากกว่าเดิม
    # Ratio < 1: โมเดลใหม่ "มั่นใจ" ในคำตอบนี้ลดลง
    # Ratio = 1: โมเดลยังคิดเหมือนเดิมเป๊ะ
    # Reward: "คำตอบนี้ได้กี่คะแนน?"
    # Ratio: "ตอนนี้โมเดลใหม่เปลี่ยนไปจากเดิมแค่ไหนเมื่อเทียบกับร่างเก่า?"
    # ข้อมูลทั้งสองส่วนนี้จะถูกนำไปรวมกันในบรรทัดถัดไป (Clipped Loss)
    # เพื่อตัดสินใจว่าจะอัปเดตน้ำหนักโมเดลอย่างไรให้ "ดีขึ้น" แต่ไม่ "เปลี่ยนไปมากจนเกินไป"
    ratio = torch.exp(new_logprob - old_logprob)

    # clipping
    # ขั้นตอนที่ทำให้การฝึกฉลาดและเสถียรกว่า Reinforcement Learning แบบปกติ
    # เพราะมันช่วยคุมไม่ให้โมเดลเปลี่ยนตัวเองเร็วเกินไปจน "เสียคน" (Model Collapse)
    # เพื่อจำกัดเพดานการเปลี่ยนไปของโมเดล
    # คำอธิบาย: ratio คือความต่างระหว่างโมเดลใหม่และเก่า บรรทัดนี้บอกว่า
    # ถ้าโมเดลใหม่จะมั่นใจในคำตอบเดิมมากขึ้น ก็ให้เพิ่มได้ไม่เกิน 20% (1.2)
    # และถ้าจะมั่นใจน้อยลง ก็ห้ามลดลงเกิน 20% (0.8)
    # เพื่อป้องกันไม่ให้การอัปเดตเพียงครั้งเดียวเปลี่ยนพฤติกรรมโมเดลไปอย่างรุนแรงจนกู่ไม่กลับ
    clip_eps = 0.2
    clipped = torch.clamp(ratio, 1 - clip_eps, 1 + clip_eps)

    # วัดระยะห่างทางสถิติระหว่างโมเดลใหม่และเก่า
    # คำอธิบาย: ในทางคณิตศาสตร์ ผลต่างของ Log-probability คือค่าประมาณของ KL Divergence
    # ซึ่งเป็นตัวบอกว่า "โมเดลใหม่เพี้ยนไปจากร่างเดิมแค่ไหน"
    kl = new_logprob - old_logprob

    # การคำนวณ Loss (PPO Objective)
    # บรรทัดนี้คือสูตรที่ทำให้ PPO โด่งดังครับ มีองค์ประกอบสำคัญ 3 ส่วน:
    # torch.min(...): เป็นการมองโลกในแง่ร้าย (Pessimistic Bound)
    # โดยเลือกค่าที่ต่ำที่สุดระหว่าง Ratio ปกติ กับ Ratio ที่ถูก Clip ไว้
    # เพื่อให้แน่ใจว่าเราจะไม่อัปเดตน้ำหนักเกินขอบเขตที่ปลอดภัย
    # - 0.01 * kl: คือการปรับโทษ (Penalty)
    # ถ้าโมเดลใหม่พยายามจะเปลี่ยนตัวเองให้ต่างจากเดิมมากเกินไป (KL สูง) ค่านี้จะไปดึงให้ Objective ต่ำลง
    # เครื่องหมาย - (หน้าสุด): เนื่องจากเราต้องการเพิ่ม Reward ให้สูงสุด (Maximize)
    # แต่ Optimizer ทำหน้าที่ลดค่า (Minimize) เราจึงต้องใส่เครื่องหมายลบเพื่อกลับด้าน
    loss = -(torch.min(ratio * reward, clipped * reward) - 0.01 * kl).mean()

    # การอัปเดตน้ำหนัก (Standard Step)
    # นำค่าความผิดพลาดที่คำนวณได้ไปปรับจูนพารามิเตอร์ภายในของ policy_model จริงๆ เพื่อให้รอบหน้ามันตอบได้ถูกใจกรรมการมากขึ้น
    optimizer.zero_grad()
    loss.backward()
    optimizer.step()

    # update old policy
    # การอัปเดตร่างเก่า (Update Reference)
    # หลังจากที่เราอัปเดตร่างใหม่จนเก่งขึ้นแล้ว เราจะก๊อปปี้มันมาไว้ใน policy_old
    # เพื่อใช้เป็น "เกณฑ์มาตรฐานใหม่" สำหรับการฝึกใน Step ถัดไป
    # .eval() บังคับให้ร่างเก่าอยู่ในโหมดประเมินผลเสมอ เพื่อไม่ให้พารามิเตอร์ของมันขยับเขยื้อนโดยไม่ตั้งใจ
    policy_old = copy.deepcopy(policy_model).eval()

    # การคืนค่าผลลัพธ์
    # ส่งค่าเลข Loss และข้อความที่ AI ตอบ กลับออกไปเพื่อนำไป Print ดูความคืบหน้าในหน้าจอ Console
    # เปรียบเสมือน "โซ่ล่ามที่ยืดหยุ่น" ครับ:
    # เราอยากให้นักเรียน (Model) พัฒนาตามคำชมของครู (Reward)
    # แต่เราต้องล่ามโซ่ไว้ (Clipping & KL) ไม่ให้เขาวิ่งไปเร็วเกินไป
    return loss.item(), text

