        # หมายความว่าตอนคำนวณ Loss โมเดลจะไม่ต้องสนใจส่วนนี้ มันจะเรียนรู้ที่จะทำนายเฉพาะส่วนที่เป็น Response (คำตอบของ AI) เท่านั้น
        # เพราะไม่ต้องการสอนให้โมเดลเรียนรู้วิธีการเขียนคำถามของมนุษย์
        labels[:, :prompt_len] = -100
        print(count,"labels =",labels)

     
        # การประมวลผลบน Device ย้ายข้อมูล Input ทั้งหมดไปที่ GPU (หรือ CPU)
        # การใช้ Dictionary Comprehension ใน Python เพื่อย้ายข้อมูลทั้งหมดที่อยู่ในตัวแปร inputs ไปยัง GPU/CPU ครับ
        # inputs คืออะไร?: เมื่อเราสั่ง policy_tokenizer(...) ผลลัพธ์ที่ได้จะเป็น Dictionary ที่ข้างในมี Tensor หลายตัว เช่น:
        # input_ids: รหัสตัวเลขของคำ
        # attention_mask: ตัวบอกว่าตำแหน่งไหนเป็นคำจริง ตำแหน่งไหนเป็น Padding
        # ทำไมต้องทำแบบนี้?: ปกติข้อมูลที่ออกมาจาก Tokenizer จะถูกสร้างขึ้นบน RAM (CPU)
        # แต่ตัวโมเดลของเราถูกส่งไปรอที่ GPU (device) แล้ว หากเราส่งข้อมูลที่อยู่บนคนละที่กันให้โมเดลประมวลผล โปรแกรมจะ Error ทันที
        # for k, v in inputs.items(): วนลูปหยิบ "ชื่อ" (Key) และ "ข้อมูล" (Value/Tensor) ออกมาทีละคู่
        # v.to(device): สั่งให้ Tensor ตัวนั้นย้ายตัวเองไปที่ device (เช่น cuda:0)
        # {k: v.to(device) ...}: สร้าง Dictionary ชุดใหม่ที่ข้างในเป็นข้อมูลที่อยู่บน GPU เรียบร้อยแล้ว
        inputs = {k: v.to(device) for k, v in inputs.items()}

        # ย้ายเฉลยไปที่อุปกรณ์เดียวกัน
        labels = labels.to(device)

        # การคำนวณและอัปเดตโมเดล (Forward & Backward) ส่งข้อมูลเข้าโมเดล (Forward Pass) 
        # เพื่อให้โมเดลลองทำนายและคำนวณค่า Loss ออกมาเทียบกับเฉลยที่ Mask ไว้
        outputs = policy_model(**inputs, labels=labels)

        # ดึงค่าความผิดพลาด (Loss) ออกมา
        loss = outputs.loss

        # ล้างค่าความชัน (Gradients) เก่าที่ค้างอยู่จากการฝึกรอบที่แล้ว
        optimizer.zero_grad()

        # คำนวณหาว่าพารามิเตอร์ตัวไหนในโมเดลที่ทำให้เกิดความผิดพลาด (Backpropagation)
        loss.backward()

        # ปรับจูนค่าน้ำหนัก (Weights) ของโมเดลเล็กน้อยตามที่ Optimizer คำนวณ เพื่อให้รอบหน้าโมเดลตอบได้แม่นยำขึ้น
        optimizer.step()

