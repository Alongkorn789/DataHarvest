# การหาว่า "โมเดลคิดว่าประโยคที่เพิ่งพูดออกมานั้น มีโอกาสเกิดขึ้นได้มากน้อยแค่ไหน" 
# โดยคิดออกมาเป็นค่าความน่าจะเป็นในรูปของ Log (Log-Probability)
def compute_log_probs(model, input_ids):

    # ส่งประโยค (input_ids) เข้าไปในโมเดลเพื่อทำการทำนาย
    # สิ่งที่ได้ Logits ซึ่งเป็นคะแนนดิบ (Raw scores) ที่โมเดลคำนวณได้สำหรับทุกๆ คำในพจนานุกรม ในทุกตำแหน่งของประโยค
    outputs = model(input_ids)

    # การเลื่อนตำแหน่ง (Shifting) เพื่อหา "คำถัดไป"
    # โมเดลภาษา (Causal LM) ถูกฝึกมาให้ทำนาย "คำถัดไป" เสมอ
    # logits[:, :-1, :]: เราตัดตัวทำนายสุดท้ายออก เพราะคำสุดท้ายในประโยคไม่มี "คำถัดไป" ให้เราเอาไปเทียบเป็นเฉลยแล้ว
    # labels[:, 1:]: เราตัดคำแรกของประโยคออก เพราะเราต้องการใช้คำที่ 2 เป็นต้นไปมาเป็น "เฉลย" ให้กับตัวทำนายที่ออกมาจากคำที่ 1
    # สรุป: เป็นการขยับให้ "ตัวทำนาย" ตรงกับ "คำเฉลย" จริงๆ ที่ปรากฏในประโยค
    logits = outputs.logits[:, :-1, :]
    labels = input_ids[:, 1:]

    # แปลงคะแนนดิบ (Logits) ให้กลายเป็นค่า ความน่าจะเป็น (Probability)
    # ทำไมต้อง Log?: เราใช้ log_softmax แทน softmax ปกติ เพราะในการคำนวณ Deep Learning
    # ค่า Log ช่วยป้องกันปัญหาตัวเลขน้อยเกินไปจนกลายเป็นศูนย์ (Numerical Stability)
    # และเปลี่ยนการคูณความน่าจะเป็นให้กลายเป็นการบวกแทน
    log_probs = torch.log_softmax(logits, dim=-1)

    # บรรทัดนี้คือการเลือกค่า Log-prob เฉพาะคำที่โมเดลพูดออกมาจริงๆ
    selected = log_probs.gather(2, labels.unsqueeze(-1)).squeeze(-1)

    # รวมค่าความน่าจะเป็นของทุกคำในประโยคให้กลายเป็น คะแนนก้อนเดียว
    # หลักการ: ตามหลักสถิติ ความน่าจะเป็นของเหตุการณ์ที่เกิดขึ้นต่อเนื่องกัน (คำที่ 1, 2, 3...) คือการนำความน่าจะเป็นมาคูณกัน
    # แต่เนื่องจากเราอยู่ในรูปของ Log เราจึงใช้การ บวก (Sum) แทนครับ
    # สูตร: log(P_1 * P_2) = log(P_1) + log(P_2)
    # ฟังก์ชันนี้จะตอบคำถามที่ว่า: "โมเดลมีความมั่นใจแค่ไหนในประโยคนี้?"
    # ถ้าค่าที่ return ออกมามีค่า ติดลบน้อยๆ (เช่น -5.0) แปลว่าโมเดลมั่นใจมาก มักจะพูดประโยคนี้
    # ถ้าค่าที่ return ออกมามีค่า ติดลบเยอะๆ (เช่น -100.0) แปลว่าโมเดลมองว่าประโยคนี้ประหลาดมาก ไม่น่าจะเกิดขึ้นได้
    # ใน PPO เราจะเอาค่านี้ของโมเดลใหม่ ไปลบกับโมเดลเก่า เพื่อดูว่าโมเดล "เปลี่ยนใจ" จากเดิมไปมากน้อยแค่ไหน
    return selected.sum(dim=1)

