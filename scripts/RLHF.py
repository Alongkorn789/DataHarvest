# ฟังก์ชัน Helper ในการทำ Fine-tuning ทำหน้าที่แยกส่วนที่เป็น "คำถาม" ออกจาก "คำตอบ"
# เพื่อให้เราสามารถจัดฟอร์แมตข้อมูลให้โมเดลเรียนรู้ได้ถูกต้อง
# ประกาศฟังก์ชันชื่อ split_prompt ที่รับตัวแปร text (ซึ่งเป็นข้อความยาวๆ จาก Dataset ที่รวมทั้งคนถามและ AI ตอบไว้ด้วยกัน)
# เข้ามาประมวลผล
def split_prompt(text):
    # ใช้คำสั่ง split ตัดแบ่งข้อความออกเป็นส่วนๆ โดยใช้เครื่องหมาย \n\nAssistant: เป็นจุดตัด
    # ในชุดข้อมูล Anthropic/hh-rlhf ข้อมูลจะถูกจัดรูปแบบเป็น Human: ... \n\nAssistant: ... 
    # บรรทัดนี้จึงแยกส่วนที่เป็นฝั่งมนุษย์และฝั่ง AI ออกจากกันเก็บไว้ในลิสต์ที่ชื่อ parts
    parts = text.split("\n\nAssistant:")
    
    # สร้างส่วนที่เป็น "คำถาม" (Prompt) ขึ้นมาใหม่ เนื่องจากตัดด้วยคำว่า \n\nAssistant: คำนี้เลยหายไป
    # บรรทัดนี้จึงเอาส่วนแรก (parts[0]) มาบวกกลับเข้าไปเพื่อให้โมเดลรู้ว่า "จบคำถามของมนุษย์แล้วนะ
    # ต่อไปเป็นตาของ Assistant ตอบแล้ว"
    prompt = parts[0] + "\n\nAssistant:"

    # ดึงส่วนที่เป็น "คำตอบ" (Response) ออกมาอย่างปลอดภัย
    # เป็นการเช็คว่าถ้าตัดแล้วมีส่วนที่สองอยู่จริง (len > 1) ให้เอาส่วนนั้นมาเป็นคำตอบ
    # แต่ถ้าไม่มี (เผื่อข้อมูลผิดพลาด) ให้เป็นค่าว่าง เพื่อป้องกันโปรแกรมพัง (IndexError)
    response = parts[1] if len(parts) > 1 else ""

    # ส่งค่ากลับออกไป 2 ค่า คือส่วนที่เป็นคำถามและคำตอบ เพื่อให้นำไปใช้งานแยกกันในขั้นตอนถัดไป
    # ในการฝึก SFT หรือ RLHF จะต้องการ
    # Prompt: ส่งให้โมเดลเพื่อใช้ในการ "เริ่มพูด" (Generate)
    # Response: ใช้เป็น "เฉลย" หรือ "Target" เพื่อคำนวณ Loss
    # การแยกแบบนี้จะช่วยให้สามารถทำ Masking เพื่อบอกโมเดลว่า
    # "ไม่ต้องจำคำถามนะ (Loss = -100) ให้จำและพยายามทำนายเฉพาะส่วนที่เป็นคำตอบเท่านั้น"
    return prompt, response

