class RewardModel(nn.Module):

    # method เริ่มต้นสถานะโมดูลภายในที่ใช้ร่วมกันโดยทั้ง nn.Module และ ScriptModule
    def __init__(self):

        # การวางโครงสร้างพื้นฐานของ Reward Model (โมเดลผู้ตัดสิน)
        # โดยเป็นการนำโมเดลที่ฉลาดอยู่แล้วมาต่อเติม "ส่วนหัว" เพื่อให้ทำงานเฉพาะทาง
        # การเรียกฟังก์ชันเริ่มต้นของคลาสแม่ (nn.Module ของ PyTorch)
        # หากไม่มีบรรทัดนี้ PyTorch จะไม่สามารถติดตาม (Track) ตัวแปรต่างๆ ที่เราประกาศในโมเดลได้ 
        # ทำให้เราไม่สามารถสั่ง .to(device) เพื่อย้ายไป GPU หรือสั่งอัปเดต Weight ได้
        # เพราะระบบไม่รู้จักว่าก้อนไหนคือ Layer ของโมเดล
        super().__init__()

        # โหลดกระดูกสันหลังหรือส่วนสมองหลักจากโมเดล DistilBERT ที่ผ่านการฝึกฝนมาแล้ว (Pre-trained)
        # ทำหน้าที่เป็น Feature Extractor คือการรับข้อความเข้าไปแล้วแปลงให้กลายเป็นเวกเตอร์ตัวเลขที่มีความหมาย (Contextual Embeddings)
        # DistilBERT (Distilled version) เล็กและเร็วเหมาะกับการนำมาทำเป็น Reward Model ที่ต้องรันซ้ำๆ หลายรอบในขั้นตอน PPO
        self.backbone = AutoModel.from_pretrained("distilbert-base-uncased")

        # สร้างเลเยอร์ใหม่ (Linear Layer) มาแปะไว้ที่ส่วนท้ายสุดของ Backbone
        # Input (hidden_size) รับเวกเตอร์สรุปความหมาย (จากตำแหน่ง [CLS]) ซึ่งปกติจะมีขนาด 768 มิติ (DistilBERT)
        # Output (1) บีบข้อมูลทั้งหมดให้เหลือเพียง "ตัวเลขเดียว" เท่านั้น
        # ความหมายใน RLHF ตัวเลขเดียวที่ได้ออกมานี้คือ Reward Score (คะแนนความพึงพอใจ) ที่บอกว่าคำตอบนี้ดีแค่ไหน
        # ยิ่งคะแนนสูงแสดงว่าโมเดลชอบคำตอบนั้นมาก
        self.value_head = nn.Linear(self.backbone.config.hidden_size, 1)

    #def forward(self, input_ids, attention_mask):
    def forward(self, input_ids=None, attention_mask=None, **kwargs):

        # การนำข้อมูล (Tokens) วิ่งผ่านชั้นเลเยอร์ต่างๆ ของ DistilBERT
        # ยังไม่ใช่การฝึกในทันทีแต่คือการ Forward Pass เพื่อสกัดเอา "ความหมาย" หรือ "ความสัมพันธ์" ของคำในประโยคออกมา
        # outputs จะเก็บค่าที่เรียกว่า Hidden States ซึ่งเป็นตัวเลขเชิงเวกเตอร์ที่แทนความหมายของคำในหลายมิติ
        outputs = self.backbone(input_ids=input_ids, attention_mask=attention_mask)

        # cls  (Classification Token) ในโมเดลตระกูล BERT ทุกๆประโยคที่ถูกใส่เข้าไปจะต้องมี Token พิเศษไว้หน้าสุดเสมอนั่นคือ [CLS]
        # โมเดล BERT ถูกฝึกมาให้ใช้ [CLS] เป็นตัว "สรุปใจความสำคัญ" ของทั้งประโยค
        # ต้องเอาจากเลเยอร์สุดท้าย เพราะเลเยอร์สุดท้ายได้ผ่านการคำนวณความสัมพันธ์ระหว่างคำ (Attention) มามากแล้ว
        # ทำให้เวกเตอร์ของ [CLS] มีความเข้าใจภาพรวมของประโยคได้ดีที่สุด
        # last_hidden_state เป็น Tensor 3 มิติ
        # มิติที่ 1 - Batch Size: หมายถึงเราเอา "ทุกประโยค" ในรอบนั้นๆ (ถ้าใส่มา 8 ประโยค ก็เอาทั้ง 8)
        # มิติที่ 2 - Sequence Length:  เลข 0 คือการระบุว่าเอาเฉพาะ Token ตัวแรกสุดของประโยคซึ่งก็คือตำแหน่งของ [CLS]
        # ถ้าเปลี่ยนเป็น 1 หรือ 2 จะเป็นการดึงเวกเตอร์ของคำถัดๆ ไปในประโยค
        # มิติที่ 3 - Hidden Size: หมายถึงจำนวนตัวเลขในเวกเตอร์(จำนวนตัวเลขในแต่ละ token) (สำหรับ DistilBERT คือ 768 ค่า)
        # สรุป "จากข้อมูลผลลัพธ์ทั้งหมด ให้ไปดึงเอาเวกเตอร์สรุปความหมาย (CLS) ที่อยู่หน้าสุดของทุกประโยคมา (token แรกของประโยค)"
        cls = outputs.last_hidden_state[:, 0, :]

        #เมื่อได้เวกเตอร์ cls (ซึ่งมีขนาด 768) จะส่งมันเข้า Linear Layer (value_head) เพื่อบีบตัวเลข 768 ตัวนั้นให้เหลือ ตัวเลขเพียงตัวเดียว (Scalar)
        #ตัวเลขตัวเดียวนี้คือ "คะแนนความพึงพอใจ" (Reward Score)
        #ยิ่งตัวเลขนี้สูง แสดงว่า Reward Model มองว่าคำตอบนี้ "ดี" หรือ "สุภาพ" ตามที่มันถูกฝึกมา
        return self.value_head(cls)

# เริ่มต้นสถานะภายในของโมดูล
reward_model = RewardModel().to(device)

