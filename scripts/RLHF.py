    # แต่ในขั้นตอน PPO ต้องการให้โมเดลหัดคิดคำตอบเอง เราจึงไม่สนใจคำตอบเฉลย (response) และใช้เครื่องหมาย _ เพื่อละทิ้งค่านั้นไป
